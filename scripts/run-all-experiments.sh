#!/bin/bash
# PostgreSQL Performance Experiments - Master Run Script
# Executes every experiments/*/run.sh in order with per-experiment logging.
#
# Usage:
#   scripts/run-all-experiments.sh            # run all experiments
#   scripts/run-all-experiments.sh 02 05      # run only experiments 02 and 05
#   DRY_RUN=1 scripts/run-all-experiments.sh  # print commands without executing

set -o pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib/common.sh"
require_cmd psql pgbench

# Create results directory
RESULTS_DIR="$REPO_ROOT/reports/runs/$(date +'%Y%m%d_%H%M%S')"
mkdir -p "$RESULTS_DIR"

log "PostgreSQL Performance Experiments - Starting Full Suite"
log "Results will be saved to: $RESULTS_DIR"

# Test database connection
log "Testing database connection..."
if [ "${DRY_RUN:-0}" = "1" ] || run_psql "$PRIMARY_HOST" "$MONITOR_DB" -c "SELECT version();" > /dev/null 2>&1; then
    success "Database connection established"
else
    error "Cannot connect to database. Please check config/local.env."
    exit 1
fi

# Select experiments: all by default, or those whose number prefix was given
EXPERIMENTS=()
for dir in "$REPO_ROOT"/experiments/*/; do
    name=$(basename "$dir")
    if [ $# -eq 0 ]; then
        EXPERIMENTS+=("$name")
    else
        for want in "$@"; do
            [ "${name%%-*}" = "$want" ] && EXPERIMENTS+=("$name")
        done
    fi
done

PASSED=()
FAILED=()
for name in "${EXPERIMENTS[@]}"; do
    runner="$REPO_ROOT/experiments/$name/run.sh"
    log "=== Running Experiment: $name ==="
    if [ ! -f "$runner" ]; then
        warning "$name has no run.sh, skipping"
        continue
    fi
    if bash "$runner" 2>&1 | tee "$RESULTS_DIR/$name.log"; then
        success "$name completed"
        PASSED+=("$name")
    else
        error "$name failed (see $RESULTS_DIR/$name.log)"
        FAILED+=("$name")
    fi
done

# Generate summary report
log "=== Generating Summary Report ==="
{
    echo "# PostgreSQL Performance Experiments - Execution Summary"
    echo
    echo "**Execution Date**: $(date)"
    echo "**Dry Run**: ${DRY_RUN:-0}"
    echo
    echo "## Experiments"
    echo
    for name in "${PASSED[@]}"; do echo "- **PASS** \`$name\` - [\`$name.log\`]($name.log)"; done
    for name in "${FAILED[@]}"; do echo "- **FAIL** \`$name\` - [\`$name.log\`]($name.log)"; done
    echo
    echo "## Next Steps"
    echo
    echo "1. Review individual log files for detailed results"
    echo "2. Compare performance metrics with experiments/*/results.md"
    echo
    echo "Generated by: PostgreSQL Performance Experiments Suite"
} > "$RESULTS_DIR/EXPERIMENT_SUMMARY.md"

# Display quick summary
echo
echo "=== QUICK SUMMARY ==="
echo "Experiments passed: ${#PASSED[@]}"
echo "Experiments failed: ${#FAILED[@]}"
echo "Results directory: $RESULTS_DIR"
echo "Summary report: $RESULTS_DIR/EXPERIMENT_SUMMARY.md"
echo

if [ ${#FAILED[@]} -gt 0 ]; then
    error "Failed: ${FAILED[*]}"
    exit 1
fi
log "Experiment suite execution completed!"
